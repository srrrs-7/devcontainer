import { getPrisma } from "../../src";

/**
 * ロールと権限の関連付けをシードする
 * 暗黙的N:Nリレーション（_PermissionToRole）を使用
 */
export async function seedRolePermissions() {
  const prisma = getPrisma();

  // ロールごとに権限をグループ化
  const rolePermissionMap: Record<string, string[]> = {
    // システム管理者: すべての権限
    "40000000-0000-0000-0000-000000000001": [
      "50000000-0000-0000-0000-000000000001", // view_organization
      "50000000-0000-0000-0000-000000000002", // edit_organization
      "50000000-0000-0000-0000-000000000003", // view_client
      "50000000-0000-0000-0000-000000000004", // edit_client
      "50000000-0000-0000-0000-000000000005", // view_user
      "50000000-0000-0000-0000-000000000006", // edit_user
      "50000000-0000-0000-0000-000000000007", // view_application
      "50000000-0000-0000-0000-000000000008", // create_application
      "50000000-0000-0000-0000-000000000009", // approve_application
      "50000000-0000-0000-0000-000000000010", // view_audit_log
    ],

    // 組織管理者: 組織とクライアント、ユーザーの管理
    "40000000-0000-0000-0000-000000000002": [
      "50000000-0000-0000-0000-000000000001", // view_organization
      "50000000-0000-0000-0000-000000000002", // edit_organization
      "50000000-0000-0000-0000-000000000003", // view_client
      "50000000-0000-0000-0000-000000000004", // edit_client
      "50000000-0000-0000-0000-000000000005", // view_user
      "50000000-0000-0000-0000-000000000006", // edit_user
    ],

    // クライアント管理者: クライアントとユーザー、申請の管理
    "40000000-0000-0000-0000-000000000003": [
      "50000000-0000-0000-0000-000000000003", // view_client
      "50000000-0000-0000-0000-000000000004", // edit_client
      "50000000-0000-0000-0000-000000000005", // view_user
      "50000000-0000-0000-0000-000000000006", // edit_user
      "50000000-0000-0000-0000-000000000007", // view_application
      "50000000-0000-0000-0000-000000000009", // approve_application
    ],

    // 一般ユーザー: 基本的な閲覧と申請作成
    "40000000-0000-0000-0000-000000000006": [
      "50000000-0000-0000-0000-000000000005", // view_user
      "50000000-0000-0000-0000-000000000007", // view_application
      "50000000-0000-0000-0000-000000000008", // create_application
    ],

    // 閲覧専用ユーザー: 閲覧権限のみ
    "40000000-0000-0000-0000-000000000007": [
      "50000000-0000-0000-0000-000000000005", // view_user
      "50000000-0000-0000-0000-000000000007", // view_application
    ],

    // 申請承認者: 申請の閲覧と承認
    "40000000-0000-0000-0000-000000000008": [
      "50000000-0000-0000-0000-000000000007", // view_application
      "50000000-0000-0000-0000-000000000009", // approve_application
    ],

    // 監査担当者: 監査ログ閲覧
    "40000000-0000-0000-0000-000000000009": [
      "50000000-0000-0000-0000-000000000010", // view_audit_log
    ],
  };

  console.log("🌱 Seeding role permissions...");

  let totalCount = 0;
  for (const [roleId, permissionIds] of Object.entries(rolePermissionMap)) {
    // 各ロールに権限を接続（暗黙的N:Nリレーション）
    await prisma.role.update({
      where: { id: roleId },
      data: {
        permissions: {
          set: permissionIds.map((id) => ({ id })),
        },
      },
    });
    totalCount += permissionIds.length;
  }

  console.log(
    `✅ Successfully seeded ${totalCount} role-permission relationships`,
  );
}
